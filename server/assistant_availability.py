"""Configuration and resource checks, never a claim that inference succeeded."""
from server.local_resources import MIN_FREE_BYTES, free_memory_bytes


def availability(gateway):
    status = gateway.status()
    if not status.get("configured"):
        return "not_configured"
    if status.get("provider") == "ollama" and status.get("local_only"):
        available = free_memory_bytes()
        if type(available) is not int:
            return "memory_unavailable"
        if available < MIN_FREE_BYTES:
            return "low_memory"
    return "configured"


