#!/usr/bin/env python3
"""Subset the bundled fonts to the characters the interface uses (U19).

    python scripts/subset_fonts.py            # regenerate frontend/src/shared/fonts/

The @fontsource "latin" files carry about 230 glyphs each; the interface
needs the printable ASCII range, Latin-1 accents (dataset names), the
general punctuation the reports use, the currency and the comparison
signs. The subsets are committed so the build needs no font tooling;
rerun this after a font upgrade. Needs `fonttools` and `brotli`.
"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "frontend" / "node_modules" / "@fontsource"
TARGET = ROOT / "frontend" / "src" / "shared" / "fonts"
FACES = [("fira-sans", "Fira Sans", 400), ("fira-sans", "Fira Sans", 500),
         ("fira-sans", "Fira Sans", 600), ("fira-code", "Fira Code", 400),
         ("fira-code", "Fira Code", 500)]
# Printable ASCII, Latin-1 (accented names, ×, ÷, °, ±), general punctuation
# (dashes, quotes, ellipsis, bullet), per mille, euro, trade mark, arrows,
# minus, division slash, almost equal, not equal, at most / at least.
UNICODES = ("U+0020-007E,U+00A0-00FF,U+2010-2027,U+2030,U+2039-203A,U+2044,U+20AC,"
            "U+2122,U+2190-2193,U+2212,U+2215,U+2248,U+2260,U+2264-2265")


def main():
    TARGET.mkdir(parents=True, exist_ok=True)
    css = ["/* Generated by scripts/subset_fonts.py from @fontsource; do not edit. */"]
    for family, name, weight in FACES:
        stem = f"{family}-latin-{weight}-normal"
        source = SOURCE / family / "files" / f"{stem}.woff2"
        out = TARGET / f"{stem}.woff2"
        subprocess.run([sys.executable, "-m", "fontTools.subset", str(source),
                        f"--output-file={out}", "--flavor=woff2", f"--unicodes={UNICODES}",
                        "--layout-features=*", "--no-hinting", "--desubroutinize"], check=True)
        css.append(f"@font-face {{\n  font-family: '{name}';\n  font-style: normal;\n"
                   f"  font-display: swap;\n  font-weight: {weight};\n"
                   f"  src: url(./{stem}.woff2) format('woff2');\n}}")
        print(f"{stem}: {source.stat().st_size:,} -> {out.stat().st_size:,} bytes")
    (TARGET / "fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
