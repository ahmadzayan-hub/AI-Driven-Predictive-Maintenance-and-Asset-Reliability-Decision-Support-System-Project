import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { dashMessages } from '../src/features/dashboard/messages'
import { jarvisDashboardMessages } from '../src/i18n/jarvisDashboard'
import { jarvisMessages } from '../src/i18n/jarvis'

for (const locale of ['en', 'ar'] as const) test(`unified dashboard, chart scope and saved view (${locale})`, async ({ page }) => {
  test.setTimeout(90_000)
  const d = dashMessages[locale], j = jarvisMessages[locale], bridge = jarvisDashboardMessages[locale]
  await page.addInitScript(language => {
    localStorage.setItem('aos-onboarded', '1'); localStorage.setItem('aos-locale', language); localStorage.setItem('aos-theme', 'light')
  }, locale)
  const runs = (await (await page.request.get('/api/runs')).json()).runs
  const run = runs.find((r: { dataset_name: string }) => r.dataset_name === 'SYNTHETIC_maintenance_review.csv')
  expect(run).toBeTruthy()
  await page.goto(`/#/dashboard/${run.id}/breakdown?by=Asset_ID`)
  await expect(page.locator('.dash-coverage')).toContainText('3')
  await page.getByRole('button', { name: bridge.open, exact: true }).click()
  const assistant = page.locator('.dash-jarvis__assistant')
  await assistant.getByRole('button', { name: j.cost, exact: true }).click()
  await assistant.getByRole('button', { name: j.ask, exact: true }).click()
  await expect(assistant.locator('.jarvis__evidence')).toContainText('500')
  await page.locator('.dash-page .dash-bars').getByRole('button', { name: /SYN-C/ }).click()
  await expect(page).toHaveURL(/f.Asset_ID=SYN-C/)
  await expect(assistant.locator('.jarvis__evidence')).toHaveCount(0)
  await expect(assistant.getByRole('status')).toHaveText(bridge.changed)
  await page.getByRole('button', { name: bridge.open, exact: true }).click()
  await assistant.getByRole('button', { name: j.cost, exact: true }).click()
  await assistant.getByRole('button', { name: j.ask, exact: true }).click()
  await expect(assistant.locator('.jarvis__evidence')).toContainText('80')
  await expect(assistant.locator('.jarvis__evidence')).toContainText('SYN-C')
  await expect(assistant.locator('.jarvis-core')).toBeVisible()
  await expect(assistant.locator('.jarvis-core')).toHaveAttribute('data-state', 'ready')
  await assistant.getByRole('button', { name: j.reduceMotion, exact: true }).click()
  await expect(assistant.locator('.jarvis-core')).toHaveAttribute('data-still', 'true')
  await assistant.locator('.jarvis__measures summary').click()
  await expect(assistant.getByRole('table')).toContainText('80')
  await expect(assistant.getByRole('table')).toContainText(j.currencyUnknown)
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.getByRole('heading', { name: d['dash.title'], exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: `../docs/screenshots/jarvis-dashboard-${locale}.png`, fullPage: true })
  await page.setViewportSize({ width: 375, height: 812 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  await page.screenshot({ path: `../docs/screenshots/jarvis-dashboard-${locale}-phone.png`, fullPage: true })
  await assistant.locator('.jarvis-core').scrollIntoViewIfNeeded()
  await page.screenshot({ path: `../docs/screenshots/jarvis-voice-console-${locale}-phone.png` })
  await page.getByRole('button', { name: bridge.close, exact: true }).click()
  await page.getByRole('button', { name: d['dash.view.save'], exact: true }).click()
  await expect(page.locator('.dash-view__notice')).toHaveText(d['dash.view.saved'])
  await page.goto(`/#/dashboard/${run.id}`)
  await expect(page).toHaveURL(/f.Asset_ID=SYN-C/)
  await page.getByRole('button', { name: d['dash.view.forget'], exact: true }).click()
  for (const view of ['overview', 'breakdown', 'trend', 'distribution', 'relationship', 'records']) {
    await page.goto(`/#/dashboard/${run.id}/${view}`)
    await expect(page.locator('.dash-page .skeleton')).toHaveCount(0)
    await expect(page.locator('.dash-coverage')).toContainText('3')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
    if (['overview', 'trend'].includes(view)) await page.screenshot({ path: `../docs/screenshots/jarvis-dashboard-${locale}-${view}.png` })
  }
  await page.setViewportSize({ width: 1440, height: 1050 })
  await page.goto(`/#/dashboard/${run.id}/overview`)
  await expect(page.locator('.exec-featured')).toBeVisible()
  await page.getByRole('button', { name: bridge.open, exact: true }).click()
  await assistant.getByRole('button', { name: j.cost, exact: true }).click()
  await assistant.getByRole('button', { name: j.ask, exact: true }).click()
  await expect(assistant.locator('.jarvis__evidence')).toContainText('500')
  await assistant.locator('.jarvis-core').scrollIntoViewIfNeeded()
  await page.screenshot({ path: `../docs/screenshots/jarvis-voice-console-${locale}.png` })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  expect(await assistant.locator('.jarvis-core__arc').evaluate(el => getComputedStyle(el).animationName)).toBe('none')
})
